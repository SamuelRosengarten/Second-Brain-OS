const noun = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** One sentence from the real counts: nothing here is generated by a model. */
function summary(b: Briefing): string {
  const { dueToday: t, overdue: o, awaitingReview: r } = b.counts;
  const first =
    t && o ? `${capitalize(numberWord(t))} ${noun(t, "task is", "tasks are")} due today and ${numberWord(o)} ${noun(o, "is", "are")} overdue.`
    : t ? `${capitalize(numberWord(t))} ${noun(t, "task is", "tasks are")} due today.`
    : o ? `${capitalize(numberWord(o))} ${noun(o, "task is", "tasks are")} overdue.`
    : "Nothing is due today.";
  const second = r ? `${capitalize(numberWord(r))} ${noun(r, "capture is", "captures are")} waiting for your review.` : "Your inbox is clear.";
  return `${first} ${second}`;
}

function greeting(hour: number): string {
  return hour < 5 ? "Working late." : hour < 12 ? "Good morning." : hour < 18 ? "Good afternoon." : "Good evening.";
}

function whenLabel(iso: string, today: string): string {
  const d = new Date(iso);
  const local = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  if (local === today) return `Today ${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
  if (local === addDays(today, -1)) return "Yesterday";
  return shortMonthDay(local);
}

function dueLabel(due: string | null, today: string): { text: string; tone: "late" | "today" | "plain" } {
  if (!due) return { text: "No date", tone: "plain" };
  if (due < today) return { text: `Overdue · ${shortDow(due)}`, tone: "late" };
  if (due === today) return { text: "Today", tone: "today" };
  return { text: dowDay(due), tone: "plain" };
}
const TONE = { late: "text-danger", today: "text-warn", plain: "text-faint" } as const;

function FocusRow({ task, today, onComplete }: { task: Task; today: string; onComplete: (id: string) => void }) {
  const { projects, colorOf } = useProjects();
  const project = projects.find((p) => p.id === task.project_id);
  const due = dueLabel(task.due_date, today);
  return (
    <li className="flex min-h-[60px] items-center gap-1.5 border-t border-line py-1 pr-3.5 pl-1 first:border-t-0 lg:min-h-[54px] lg:gap-3 lg:py-0 lg:pr-4 lg:pl-3">
      <TaskCircle label={`Complete: ${task.title}`} onClick={() => onComplete(task.id)} />
      <span className="flex min-w-0 flex-1 flex-col gap-0.5 lg:flex-row lg:items-center lg:gap-3">
        <span className="truncate text-[15px] lg:min-w-0 lg:flex-1 lg:text-sm">{task.title}</span>
        <span className="flex items-center gap-1.5 text-[12.5px] text-muted lg:text-xs">
          <ProjectSquare color={colorOf(task.project_id)} size={7} />
          <span className="min-w-0 truncate">{project?.name ?? "No project"}</span>
          <span className={`ml-auto font-mono text-[11.5px] whitespace-nowrap lg:min-w-24 lg:text-right ${TONE[due.tone]}`}>{due.text}</span>
        </span>
      </span>
    </li>
  );
}

/** Tasks per day for the current week, with the heaviest day called out. */
function WeekChart({ tasks, today }: { tasks: Task[]; today: string }) {
  const start = weekStart(today);
  const days = Array.from({ length: 7 }, (_, i) => addDays(start, i));
  const counts = days.map((d) => tasks.filter((t) => t.due_date === d).length);
  const total = counts.reduce((a, b) => a + b, 0);
  const future = days.map((d, i) => ({ d, n: counts[i] })).filter((x) => x.d >= today);
  const max = Math.max(0, ...future.map((x) => x.n));
  const heaviest = future.find((x) => x.n === max && max > 0);
  const lighter = heaviest ? future.filter((x) => x.d > heaviest.d && x.n <= max - 2).sort((a, b) => a.n - b.n)[0] : undefined;
  const text = total === 0 ? "Nothing is planned yet this week." : heaviest && max >= 3 && lighter ? `${fullDow(heaviest.d)} is your heaviest day. Moving one task to ${fullDow(lighter.d)} would even it out.` : "Your week looks balanced.";
  const labels = ["M", "T", "W", "T", "F", "S", "S"];
  return (
    <section aria-labelledby="wk-h" className="flex flex-col gap-3.5 rounded-xl border border-line bg-surface p-4">
      <div className="flex items-baseline gap-2">
        <h2 id="wk-h" className="m-0 text-sm font-semibold">This week</h2>
        <span className="ml-auto font-mono text-xs text-faint">{total} {noun(total, "task", "tasks")}</span>
      </div>
      <div role="img" aria-label={`Tasks per day: ${days.map((d, i) => `${shortDow(d)} ${counts[i]}`).join(", ")}`} className="grid h-[92px] grid-cols-7 items-end gap-1.5">
        {days.map((d, i) => (
          <div key={d} className="flex h-full flex-col items-center justify-end gap-1.5">
            <div className="w-full max-w-6 rounded-[5px]" style={{ height: Math.min(80, 6 + counts[i] * 15), background: d < today ? "var(--border)" : d === today ? "var(--warn)" : "var(--border-strong)" }} />
            <span className={`font-mono text-[11px] ${d === today ? "text-fg" : "text-faint"}`}>{labels[i]}</span>
          </div>
        ))}
      </div>
      <p className="m-0 text-[12.5px] text-muted">{text}</p>
    </section>
  );
}

export default function TodayPage() {
  const today = localToday();
  const toast = useToast();
  const openPalette = useOpenPalette();
  const [now, setNow] = useState<Date | null>(null);
  useEffect(() => setNow(new Date()), []);
  const briefing = useApi<Briefing>(`/api/briefing?today=${today}`);
  const proposed = useApi<{ captures: Capture[] }>("/api/captures?status=proposed");
  const notes = useApi<{ notes: NoteMeta[] }>("/api/notes?limit=3");
  const weekFrom = weekStart(today);
  const week = useApi<{ tasks: Task[] }>(`/api/tasks?due_from=${weekFrom}&due_to=${addDays(weekFrom, 6)}&limit=500`);
  const midnight = useMemo(() => { const d = new Date(); d.setHours(0, 0, 0, 0); return d.toISOString(); }, []);
  const doneToday = useApi<{ tasks: Task[] }>(`/api/tasks?status=done&completed_since=${encodeURIComponent(midnight)}`);
  const [showDone, setShowDone] = useState(false);
  const [gone, setGone] = useState<Set<string>>(new Set());

  const b = briefing.data;
  const reload = () => { void briefing.reload(); void proposed.reload(); void notes.reload(); void week.reload(); void doneToday.reload(); };

  async function complete(id: string) {
    setGone((g) => new Set(g).add(id));
    try {
      await api(`/api/tasks/${id}`, { method: "PATCH", body: { status: "done" } });
      reload();
    } catch (e) {
      setGone((g) => { const n = new Set(g); n.delete(id); return n; });
      toast(e instanceof Error ? e.message : "Failed", "danger");
    }
  }

  const focus = b ? [...b.overdue, ...b.dueToday, ...b.dueSoon].filter((t) => !gone.has(t.id)).slice(0, 6) : [];
  const lastDue = focus.reduce<string | null>((m, t) => (t.due_date && (!m || t.due_date > m) ? t.due_date : m), null);
  const review = proposed.data?.captures ?? [];
  const reviewCount = b?.counts.awaitingReview ?? review.length;
  const finished = doneToday.data?.tasks ?? [];
  const nowDate = now ?? new Date();

  return (
    <div className="mx-auto flex max-w-[1200px] flex-col gap-5 lg:gap-7">
      <header className="flex items-start gap-3">
        <div className="flex min-w-0 flex-1 flex-col gap-1.5">
          <Eyebrow>{shortDow(today)} {Number(today.slice(8))} {shortMonthDay(today).split(" ")[0]} <span className="hidden lg:inline">· Week {isoWeek(today)}</span></Eyebrow>
          <h1 className="m-0 text-[30px] leading-[1.15] font-semibold tracking-[-0.025em]">{greeting(nowDate.getHours())}</h1>
          {b && <p className="m-0 max-w-[640px] text-[15px] text-pretty text-muted">{summary(b)}</p>}
        </div>
        <div className="flex gap-2 lg:hidden">
          <button type="button" onClick={openPalette} aria-label="Search" className="grid size-11 place-items-center rounded-xl border border-line bg-surface text-muted"><Search size={19} aria-hidden strokeWidth={1.8} /></button>
          <Link href="/settings" aria-label="Settings and automations" className="grid size-11 place-items-center rounded-xl border border-line bg-surface text-muted"><SlidersHorizontal size={19} aria-hidden strokeWidth={1.8} /></Link>
        </div>
      </header>

      <div className="hidden lg:block"><TodayCapture onSaved={reload} /></div>
      <Link href="/capture" className="flex min-h-[54px] items-center gap-3 rounded-[14px] border border-line bg-surface px-4 text-[15.5px] text-faint lg:hidden">
        <Plus size={18} aria-hidden strokeWidth={2} className="text-fg" />
        <span className="flex-1">Capture a thought, task or link</span>
      </Link>

      {briefing.error && <ErrorBox message={briefing.error} onRetry={reload} />}
      {briefing.loading && !b && <ListSkeleton rows={4} />}

      {b && (
        <div className="flex flex-wrap items-start gap-x-7 gap-y-5">
          <div className="flex min-w-0 flex-[2_1_480px] flex-col gap-5 lg:gap-7">
            {/* phone: the review card comes first, as in the design */}
            {reviewCount > 0 && (
              <AiPanel aria-labelledby="rv-m" className="flex flex-col gap-3 p-4 lg:hidden">
                <AiHeading id="rv-m">{reviewCount} {noun(reviewCount, "capture", "captures")} to review</AiHeading>
                <p className="m-0 text-[13.5px] text-muted">Your local model drafted titles, tags and tasks. About a minute.</p>
                <Link href="/inbox/review" className="flex min-h-[46px] items-center justify-center rounded-[11px] bg-accent text-[15px] font-semibold text-accent-fg">Start review</Link>
              </AiPanel>
            )}

            <section aria-labelledby="focus-h" className="flex flex-col gap-2 lg:gap-3">
              <div className="flex items-baseline gap-2.5">
                <h2 id="focus-h" className="m-0 text-[17px] font-semibold lg:text-[15px]">Focus</h2>
                <span className="font-mono text-xs text-faint">{focus.length} <span className="lg:hidden">left</span><span className="hidden lg:inline">open{lastDue ? ` · due by ${shortDow(lastDue)}` : ""}</span></span>
                <Link href="/plan" className="ml-auto flex min-h-11 items-center text-sm text-muted hover:text-fg lg:min-h-0 lg:text-[13px]"><span className="lg:hidden">Plan</span><span className="hidden lg:inline">Plan the week →</span></Link>
              </div>
              {focus.length === 0 ? (
                <p className="m-0 rounded-xl border border-dashed border-line px-4 py-6 text-center text-[13px] text-muted">Nothing due soon. Add due dates to your tasks, or open Plan to place them on days.</p>
              ) : (
                <ul className="m-0 list-none overflow-hidden rounded-xl border border-line bg-surface p-0 lg:rounded-xl">
                  {focus.map((t) => <FocusRow key={t.id} task={t} today={today} onComplete={(id) => void complete(id)} />)}
                </ul>
              )}
              {finished.length > 0 && (
                <>
                  <button type="button" aria-expanded={showDone} onClick={() => setShowDone((v) => !v)} className="h-8 self-start rounded-lg px-2.5 text-[12.5px] text-faint hover:text-fg">
                    {showDone ? "Hide" : "Show"} {finished.length} completed today
                  </button>
                  {showDone && (
                    <ul className="m-0 list-none overflow-hidden rounded-xl border border-line bg-surface p-0">
                      {finished.map((t) => <li key={t.id} className="flex min-h-11 items-center gap-3 border-t border-line px-4 py-2 text-sm text-faint line-through first:border-t-0">{t.title}</li>)}
                    </ul>
                  )}
                </>
              )}
            </section>

            <section aria-labelledby="notes-h" className="hidden flex-col gap-3 lg:flex">
              <div className="flex items-baseline gap-2.5">
                <h2 id="notes-h" className="m-0 text-[15px] font-semibold">Recently touched</h2>
                <Link href="/knowledge" className="ml-auto text-[13px] text-muted hover:text-fg">All notes →</Link>
              </div>
              {(notes.data?.notes.length ?? 0) === 0 ? (
                <p className="m-0 text-[13px] text-muted">No notes yet. Accept a capture from the inbox, import files, or write one in Notes.</p>
              ) : (
                <div className="grid gap-3 [grid-template-columns:repeat(auto-fit,minmax(min(200px,100%),1fr))]">
                  {notes.data!.notes.map((n) => (
                    <Link key={n.id} href={`/knowledge/${n.id}`} className="flex flex-col gap-1.5 rounded-xl border border-line bg-surface p-3.5 hover:bg-hover/50">
                      <span className="text-[13.5px] font-medium">{n.title}</span>
                      <span className="line-clamp-2 text-[12.5px] leading-[1.45] text-muted">{n.summary || "No summary yet."}</span>
                      <span className="font-mono text-[11px] text-faint">{whenLabel(n.updatedAt, today)}</span>
                    </Link>
                  ))}
                </div>
              )}
            </section>
          </div>

          <div className="hidden min-w-0 flex-[1_1_300px] flex-col gap-5 lg:flex">
            {reviewCount > 0 && (
              <AiPanel aria-labelledby="rev-h" className="flex flex-col gap-3 p-4">
                <AiHeading id="rev-h" count={reviewCount}>Waiting for your review</AiHeading>
                <p className="m-0 text-[12.5px] text-muted">Your local model drafted titles, tags and tasks. Nothing is saved until you accept it.</p>
                <ul className="m-0 flex list-none flex-col gap-1.5 p-0">
                  {review.slice(0, 3).map((c) => (
                    <li key={c.id}>
                      <Link href={`/inbox/${c.id}`} className="flex flex-col gap-0.5 rounded-[9px] bg-surface px-3 py-2.5 hover:bg-hover/60">
                        <span className="text-[13.5px]">{c.proposal?.title ?? c.content.slice(0, 60)}</span>
                        <span className="text-xs text-faint">{[c.proposal?.next_action ? "Task + note" : "Note", ...(c.proposal?.tags.slice(0, 3).map((t) => `#${t}`) ?? [])].join(" · ")}</span>
                      </Link>
                    </li>
                  ))}
                </ul>
                <Link href="/inbox" className="flex h-9 items-center justify-center rounded-[9px] border border-ai-line text-[13px] font-medium text-accent hover:bg-ai-bg">Review all {numberWord(reviewCount)}</Link>
              </AiPanel>
            )}
            <WeekChart tasks={week.data?.tasks ?? []} today={today} />
          </div>
        </div>
      )}
    </div>
  );
}
